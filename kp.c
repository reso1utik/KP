#include <stdio.h>
#include <stdlib.h>
#include <math.h>
#include <locale.h>

/**
 * Этап 1: Преобразование показания датчика Q(X)
 * @param x - текущее показание концентрации продукта (%)
 * @return вычисленное значение индикатора Q
 */
double calculate_q(double x) {
    // Ветка 1: Значения меньше 55
    if (x < 55.0) {
        return ((x - 55.0) / 2.0) + 20.0;
    }
    // Защита от неопределенности ln(0). При X = 55.00 возвращаем значение из методички
    else if (fabs(x - 55.0) < 0.0001) {
        return 49.59;
    }
    // Ветка 2: Штатный режим 55..75
    else if (x <= 75.0) {
        return 4.0 * log(x - 65.0 + 10.0) + 40.0;
    }
    // Ветка 3: Значения больше 75
    else {
        return 3.0 * sqrt(x - 75.0 + 1.0) + 65.0;
    }
}

/**
 * Этап 2: Оперативный online-контроль границ техпроцесса
 * @param q - текущее вычисленное значение индикатора Q
 * @param lcl - нижняя граница допуска
 * @param ucl - верхняя граница допуска
 * @return 1 - если НОРМА, 0 - если ТРЕВОГА
 */
int check_control(double q, double lcl, double ucl) {
    if (q < lcl || q > ucl) {
        return 0; // Выход за границы техпроцесса
    }
    return 1; // Значение в пределах допуска
}

int main(void) {
    setlocale(LC_ALL, "rus");
    // Настройки и инициализация параметров контроля (Вариант 6)
    double q0 = 49.59;               // Базовое значение Q0
    double lcl = q0 * 0.95;          // Нижняя граница допуска (-5%)
    double ucl = q0 * 1.05;          // Верхняя граница допуска (+5%)
    int total_measurements = 60;     // Всего измерений по ТЗ (N = 60)

    // Переменные для Этапа 3 и 4 (Потоковая статистика без массивов)
    int subset_size = 27;            // Размер исследуемого интервала Q[1..27]
    double subset_sum = 0.0;         // Сумма элементов для расчета среднего
    int count_above = 0;             // Количество значений строго выше среднего

    printf("[СОСТОЯНИЕ: ИНИЦИАЛИЗАЦИЯ]\n");
    printf("Контрольные параметры: Q0 = %.2f, Границы допусков: %.2f .. %.2f\n\n", q0, lcl, ucl);

    printf("[СОСТОЯНИЕ: РАБОТА]\n");
    printf("%-5s | %-10s | %-10s | %-15s\n", "Шаг", "X (%)", "Q(X)", "Статус контроля");
    printf("-------------------------------------------------------------\n");

    // ПЕРВЫЙ ПРОХОД ПОТОКА: Вывод логов и сбор суммы для вычисления Среднего
    for (int i = 0; i < total_measurements; i++) {
        double x = 0.0;

        // Имитация изменения концентрации X (технологические сценарии)
        if (i == 0)      x = 55.0;
        else if (i < 20) x = 54.8 + (i * 0.1);
        else if (i < 40) x = 45.0 - (i * 0.1);
        else             x = 74.0 + (i * 0.1);

        // Расчет индикатора процесса Q (Этап 1)
        double q = calculate_q(x);

        // Накопление суммы для элементов исследуемого диапазона [1..27]
        if (i < subset_size) {
            subset_sum += q;
        }

        // Проверка технологических границ (Этап 2)
        int is_normal = check_control(q, lcl, ucl);

        // Вывод потоковых данных (Этап 3)
        if (i < 5 || i > 55) {
            if (is_normal == 1) {
                printf("%-5d | %-10.2f | %-10.4f | НОРМА\n", i + 1, x, q);
            }
            else {
                printf("%-5d | %-10.2f | %-10.4f | ТРЕВОГА (ВЫБРОС)\n", i + 1, x, q);
            }
        }
        else if (i == 5) {
            printf("... [идет потоковая обработка данных датчика] ...\n");
        }
    }

    // Вычисляем среднее арифметическое выборки
    double mean = subset_sum / subset_size;

    // ВТОРОЙ ПРОХОД ПОТОКА: Анализ элементов на превышение среднего (без сохранения в массив)
    for (int i = 0; i < subset_size; i++) {
        double x = 0.0;
        if (i == 0) x = 55.0;
        else        x = 54.8 + (i * 0.1);

        double q = calculate_q(x);

        // Подсчет элементов строго выше среднего (Этап 4)
        if (q > mean) {
            count_above++;
        }
    }

    // Вычисление процентной доли
    double percentage = ((double)count_above / subset_size) * 100.0;

    printf("\n[СОСТОЯНИЕ: КОНЕЦ (ОСТАНОВ)]\n");
    printf("Потоковая обработка завершена. Модуль аналитики выполнил расчет.\n");

    // Итоговый аналитический вывод
    printf("\n================ РЕЗУЛЬТАТЫ СТАТИСТИКИ ================\n");
    printf("Интервал исследования: Q[1 .. 27] (Выборка: %d элементов)\n", subset_size);
    printf("1. Среднее арифметическое (Mean Q): %.4f\n", mean);
    printf("2. Кол-во измерений строго ВЫШЕ среднего: %d\n", count_above);
    printf("3. Процентная доля этих измерений: %.2f %%\n", percentage);
    printf("========================================================\n");

    return 0;
}
